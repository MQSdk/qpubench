def qiskit_version() -> str:
    """Installed Qiskit version, or "" if it isn't installed.

    Recorded per row because TN-VQE calls `transpile(circuit, backend)`
    with no optimization_level (functions_qiskit.py:47,205), and
    transpile's own default resolves to 2 in Qiskit 2.x but 1 in Qiskit
    1.x.  "Qiskit's default" is therefore a version-dependent value, so
    the version is the thing worth recording -- a Qiskit_Opt_Level column
    would be recording a number nothing can set.
    """
    try:
        return importlib.metadata.version("qiskit")
    except importlib.metadata.PackageNotFoundError:
        return ""


def qubit_count(mapper: str, active_electrons: int, active_orbitals: int) -> tuple[int, str]:
    """(qubits, provenance) for one active space under one mapper."""
    if mapper == "JW":
        return 2 * active_orbitals, "jw_exact"
    n_alpha = n_beta = active_electrons // 2
    n = count_qubits(active_orbitals, n_alpha, n_beta)
    assert n is not None
    source = "mol_map_run" if is_confirmed(active_orbitals, n_alpha, n_beta) else "mol_map_inferred"
    return n, source


def uccsd_parameter_count(num_qubits: int, num_electrons: int) -> int:
    """One variational amplitude per singles+doubles excitation.

    Counted from the pool `_ansatz_builders.build_ansatz` really builds
    (`integrations.generic_adapt_vqe.pool`) rather than from a
    combinatorial formula written out here, so the two cannot drift
    apart.  The pool is pure qpubench + stdlib, so this adds no
    dependency the generator did not already have.

    No stage-1 row uses this: UCCSD runs only on JW-mapped plain VQE, so
    it cannot be crossed with the other two methods and is out of the
    screen.  It is kept for a later stage that names UCCSD explicitly,
    where the count is what sets the row's optimizer budget -- at 12
    qubits / 8 electrons the pool is 200 operators.
    """
    from integrations.generic_adapt_vqe.pool import generate_singles_doubles_pool

    return len(generate_singles_doubles_pool(num_qubits, num_electrons))


def optimizer_iterations(
    num_params: int, evals_per_param: float = STAGE1_EVALS_PER_PARAM,
) -> int:
    """Cost-function evaluations a row's optimizer will really consume.

    `max(MIN_ITERATIONS, ceil(evals_per_param * n))`, so that every row
    reaches a comparable fraction of its own achievable descent rather
    than a fraction that shrinks with n.  The multiplier is the stage's:
    stage 1 screens at STAGE1_EVALS_PER_PARAM, stage 2 converges at
    STAGE2_EVALS_PER_PARAM.  See MIN_ITERATIONS.
    """
    budget = max(MIN_ITERATIONS, math.ceil(evals_per_param * num_params))
    # The proportional rule always clears COBYLA's simplex, so this can
    # never fire: for n <= 28 the floor of 30 does it, and for n >= 29 the
    # multiplier adds >= 8.7 evaluations against the 2 the simplex needs.
    assert budget >= num_params + SIMPLEX_OVERHEAD
    return budget


def stage_evals_per_param(stage: str) -> float:
    """The multiplier a stage's rows are budgeted at."""
    return STAGE2_EVALS_PER_PARAM if stage.startswith("2") else STAGE1_EVALS_PER_PARAM


def circuit_parameter_count(
    ansatz: str, num_qubits: int, reps: int, num_electrons: int | None = None,
) -> str:
    """Circuit-side (phi) parameter count, where the ansatz fixes it.

    Per circuit, not per family name: two circuits a task might build for
    the same nominal family can differ in their rotation layers, and
    recording one number for both is how this column came to understate
    every TN row by 50%.

    UCCSD's count depends on the excitation list its builder generates
    from the active space, not on (qubits, reps) alone, so it takes
    `num_electrons` and counts the real pool -- see
    `uccsd_parameter_count`.
    """
    if ansatz == "UCCSD":
        return "" if num_electrons is None else str(
            uccsd_parameter_count(num_qubits, num_electrons) * reps
        )
    if ansatz == "excitation_preserving_linear":
        # One RZ per qubit per rotation layer, plus one theta per linear
        # pair per rep (Qiskit's default mode="iswap"). Verified against
        # the built circuit's num_parameters, not derived on paper.
        return str(num_qubits * (reps + 1) + (num_qubits - 1) * reps)
    if ansatz == "StronglyEntanglingLayers":
        return str(3 * reps * num_qubits)          # PennyLane's (L, N, 3) shape
    if ansatz in ("EfficientSU2", "EfficientSU2_circular"):
        return str(2 * num_qubits * (reps + 1))    # 2 rotation layers per block
    if ansatz == "RealAmplitudes":
        return str(num_qubits * (reps + 1))        # 1 rotation layer per block
    return ""


def qasm_ansatz_pin(
    ansatz: str, num_qubits: int, reps: int, num_electrons: int,
) -> tuple[str, str]:
    """(path, sha256 prefix) of the pinned QASM circuit, if one exists.

    Every family is pinned, VQE's as well as TN-VQE's.  A named ansatz is
    not a circuit -- it is a name a library version resolves -- so two
    rows naming one family are comparable only if they resolve it to the
    same circuit, and a reader comparing against a method this campaign
    does not run needs the circuit rather than the name.

    Pinning the exact circuit is also what makes a cross-backend
    comparison meaningful: cebule-tn_vqe commit a760489 unified all five
    paths to an expectation value on Qiskit's `q[i] = Hamiltonian index
    i` convention, so one pinned QASM string now gives the same energy on
    both platforms and both measurement methods.  It did not before.

    The circuit lives in a file rather than a CSV cell -- a multi-line
    QASM program does not belong in one -- and the hash makes a silently
    edited circuit detectable.  Generate the files with
    `pin_qasm_ansatz.py`; both cells stay blank until you do.

    Note the interaction with TNQCOptInput.n_layers_circuit: supplying
    qasm_ansatz changes its effective default from 3 to 1.
    """
    stem = f"{ansatz}_{num_qubits}q_{reps}r"
    if ansatz == "UCCSD":
        # UCCSD's structure follows the occupied/virtual split, so the
        # electron count is part of its identity; the hardware-efficient
        # families are fixed by (qubits, reps) alone.
        stem += f"_{num_electrons}e"
    path = _QASM_DIR / f"{stem}.qasm"
    if not path.exists():
        return "", ""
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
    return str(path.relative_to(_REPO_ROOT)), digest


def _qubit_note(mapper: str, source: str, molecule: str, basis: str) -> str:
    if mapper == "JW":
        return "N_Qubit = 2 x active orbitals (exact)."
    if source == "mol_map_run":
        return f"N_Qubit confirmed by a real Cebule MOL_MAP run for {molecule}/{basis}."
    return (
        "N_Qubit predicted by hamiltonian_sources.mol_map's inferred "
        "constraint-encoding formula, not a real MOL_MAP run -- exact for "
        "all 8 counts real runs have reported, but an estimate here."
    )


def _measurement_note(method: str) -> str:
    if method == "pauli":
        return "Standard per-Pauli-string measurement (baseline)."
    if method == QESEM_NO_GROUPING:
        return (
            "The pauli/grouped dimension COLLAPSES here: QESEM returns a mitigated "
            "expectation value, never the raw bitstring distribution a grouping "
            "scheme reconstructs from, so there is nothing for 'grouped' to "
            "consume. A property of the service, not of the integration. "
            "Consequence: the campaign's most defensible headline -- 'grouped "
            "keeps measurement cost flat while number_preserving does not' -- "
            "cannot draw on the QESEM arm at all."
        )
    if method.startswith("n/a"):
        return "No quantum measurements taken, so no measurement method applies."
    return (
        "Cebule's basis-state-pair-grouping measurement scheme "
        "(TNQCOptInput.measurement_method='grouped'). Expected to need "
        "fewer or equal distinct circuits per iteration than 'pauli', but "
        "the exact circuit count is an output of a real run, not "
        "predictable from the inputs."
    )


def _tn_ansatz_note(tn_ansatz: str) -> str:
    if tn_ansatz == TNAnsatz.NUMBER_PRESERVING.value:
        return (
            "CONTROL, not a candidate: number_preserving is a strict superset "
            "of givens that is not a single-particle transformation, so U^dag H U "
            "picks up higher-body terms and many more Pauli strings. Carried to "
            "check that on hardware, not because it is expected to win; first arm "
            "to cut if budget tightens."
        )
    if tn_ansatz == TNAnsatz.GIVENS.value:
        return (
            "givens is the JW image of a single-particle orbital rotation: it "
            "entangles, commutes with the number operator, and leaves U^dag H U a "
            "two-body fermionic Hamiltonian, so its Pauli-string count saturates "
            "with TN_Layers_Network rather than growing."
        )
    if tn_ansatz.startswith("rotation_"):
        return (
            f"{tn_ansatz} is NON-ENTANGLING: the network factorises across the two "
            "wires of every M gate, so U(theta) only rotates each qubit's local "
            "basis. Kept as the comparison against the task's own default."
        )
    return ""


def _row(
    *, stage: str, mol: Molecule, basis: str, active_space: str,
    active_electrons: int, active_orbitals: int, mapper: str, method: str,
    ansatz: str, reps: int, measurement: str,
    layers_network: int | None, tn_ansatz: str,
    optimization_mode: str = "both", extra_note: str = "",
    shots: str | None = None,
    error_mitigation: str = MITIGATION_NONE,
    precision: str = SHOT_BASED,
    qesem_execution_mode: str = NOT_QESEM,
    refines_case_id: str = "",
    converged_params: tuple[str, str] = ("", ""),
) -> dict[str, str]:
    num_qubits, source = qubit_count(mapper, active_electrons, active_orbitals)
    notes = [_qubit_note(mapper, source, mol.name, basis)]
    if extra_note:
        notes.append(extra_note)
    family_note = _tn_ansatz_note(tn_ansatz)
    if family_note:
        notes.append(family_note)
    notes.append(_measurement_note(measurement))

    is_tn = method == "TN-VQE"
    # "network" freezes phi and contracts the circuit classically; it does
    # not mean there is no circuit.  The control runs the same circuit as
    # the row it controls, at the same phi_init, and that frozen state IS
    # the reference theta is optimised against -- which is why two network
    # rows differing only in their circuit give different floors.  So the
    # circuit, its reps, its pinned QASM and its phi count are all
    # recorded honestly here; what distinguishes the control is that it
    # takes no QUANTUM MEASUREMENTS, and Optimization_Mode already carries
    # that.
    takes_measurements = optimization_mode != "network"
    qasm_file, qasm_hash = qasm_ansatz_pin(ansatz, num_qubits, reps, active_electrons)
    phi_params = circuit_parameter_count(ansatz, num_qubits, reps, active_electrons)
    # Theta is fixed by the inputs, unlike Num_ExpVals_Per_Iter: it is
    # n_layers_network * ((3n - 2) // 2) * params_per_node.
    theta_params = (
        str(tn_theta_parameter_count(num_qubits, layers_network, tn_ansatz))
        if is_tn and layers_network is not None and tn_ansatz in {a.value for a in TNAnsatz}
        else ""
    )
    # The optimizer varies whatever the row leaves free: phi is frozen in
    # network mode, so only theta counts there.
    free_params = (int(phi_params) if phi_params and takes_measurements else 0) + (
        int(theta_params) if theta_params else 0
    )
    # Measurement circuits per evaluation: the row's Hamiltonian decides
    # it, so it is keyed on (mapper, molecule, qubits) and not on the
    # circuit or the method.  A network row takes no measurements at all.
    if not takes_measurements:
        expvals, expvals_source = NETWORK_NO_MEASUREMENT, NETWORK_NO_MEASUREMENT
    else:
        known = EXPVALS_PER_ITER.get((mapper, mol.name, num_qubits))
        if known is None:
            expvals, expvals_source = str(EXPVALS_ASSUMED[mapper]), "assumed"
        else:
            expvals, expvals_source = str(known[0]), known[1]

    # Keyed on the circuit family alone: a VQE row and a TN-VQE row that
    # share an ansatz start from the same phi, and so does the `network`
    # control that freezes it.  Nothing here reads `method` or
    # `optimization_mode`, which is the point.
    phi_init = (
        PHI_INIT_ZEROS if ansatz in PHI_INIT_ZEROS_ANSATZE else PHI_INIT_RANDOM
    )
    return {
        "Case_ID": "",                       # assigned after the full list is built
        "Stage": stage,
        "Molecule": mol.name,
        "Charge": "0",
        "Multiplicity": "1",
        "Num_Electrons": str(mol.num_electrons),
        "Basis": basis,
        "Basis_Source": BASIS_SOURCE[basis],
        "Active_Space": active_space,
        "Active_Electrons": str(active_electrons),
        "Active_Orbitals": str(active_orbitals),
        "Mapper": mapper,
        "N_Qubit": str(num_qubits),
        "N_Qubit_Source": source,
        "Method": method,
        "Ansatz": ansatz,
        "Ansatz_Reps": str(reps),
        "Backend_Platform": BACKEND_PLATFORM_TN if is_tn else BACKEND_PLATFORM_VQE,
        "Optimizer": OPTIMIZER,
        "Opt_Options": OPT_OPTIONS,
        "Iterations": str(
            optimizer_iterations(free_params, stage_evals_per_param(stage))
        ),
        # 0 was a real shot count where "shots do not apply" was meant --
        # and would be wrong the moment such a row were re-run in "both"
        # mode. n/a, matching what Measurement_Method already says on
        # exactly these rows.
        "Shots": shots if shots is not None else (
            str(SHOTS) if takes_measurements else NETWORK_MODE
        ),
        "Qiskit_Version": qiskit_version(),
        "TN_Layers_Network": "" if layers_network is None else str(layers_network),
        "TN_Ansatz": tn_ansatz,
        "Optimization_Mode": optimization_mode if is_tn else NOT_TN,
        "Measurement_Method": measurement,
        "Qasm_Ansatz_File": qasm_file,
        "Qasm_Ansatz_SHA256": qasm_hash,
        "Num_Opt_Params_Phi": phi_params,
        "Phi_Init": phi_init,
        "Num_Opt_Params_Theta": theta_params,
        "Num_ExpVals_Per_Iter": expvals,
        "Num_ExpVals_Source": expvals_source,
        "Error_Mitigation": error_mitigation,
        "Precision": precision,
        "QESEM_Execution_Mode": qesem_execution_mode,
        "Refines_Case_ID": refines_case_id,
        "Converged_Params_File": converged_params[0],
        "Converged_Params_SHA256": converged_params[1],
        "Notes": " ".join(notes),
    }


def stage1_active_space(mol: Molecule, basis: str) -> tuple[str, int, int, str]:
    """(label, active electrons, active orbitals, note) for one stage-1 row.

    H2 carries no restriction: every electron in every orbital the basis
    provides, so its qubit count follows the basis and the basis screen
    measures something.  The heavier molecules keep a fixed valence CAS
    for now -- provisionally, pending a decision on how far to restrict
    them, which is the reason the label is recorded per row rather than
    assumed campaign-wide.
    """
    if mol.valence_cas is None:
        active_orbitals = N_SPATIAL_ORBITALS[mol.name][basis]
        note = (
            f"NO active-space restriction: all {mol.num_electrons} electrons in "
            f"all {active_orbitals} orbitals of {basis}, so N_Qubit follows the "
            "basis set rather than being held fixed across it."
        )
        return "full", mol.num_electrons, active_orbitals, note
    active_electrons, active_orbitals = mol.valence_cas
    note = (
        f"Stage-1 screening active space CAS({active_electrons},"
        f"{active_orbitals}), held fixed across all basis sets"
        f"; {mol.core_orbitals} core orbital(s) frozen. PROVISIONAL: how far to "
        "restrict this molecule is an open campaign decision."
    )
    return "valence_cas", active_electrons, active_orbitals, note


def skips_mapper(mapper: str, active_electrons: int, active_orbitals: int) -> bool:
    """True where a row is too wide for the screen to measure.

    Jordan-Wigner only, and by qubit count: a JW row above
    MAX_JW_QUBITS is screened on mol_map alone, whose constraint
    encoding holds the same active space at far fewer qubits.  See
    MAX_JW_QUBITS for why the limit is a measurement limit rather than a
    circuit one.
    """
    if mapper != "JW":
        return False
    num_qubits, _ = qubit_count(mapper, active_electrons, active_orbitals)
    return num_qubits > MAX_JW_QUBITS


def build_stage1() -> list[dict[str, str]]:
    """Screening matrix: which basis set, which ansatz, which mapper.

    Every ansatz is run by all three methods -- plain VQE, TN-VQE in
    `both` mode, and the classical-only `network` control -- on both
    mappers, at one circuit repetition count, so that the three rows of a
    triple differ in method alone: same circuit file, same phi_init, same
    Hamiltonian.

    Per (molecule, basis, mapper) that is, for each of the two
    measurement methods, one VQE row and one TN-VQE row per ansatz, plus
    one zero-QPU control per ansatz.
    """
    rows: list[dict[str, str]] = []
    tn = STAGE1_TN_REFERENCE
    reps = tn["ansatz_reps"]
    for mol in MOLECULES:
        for basis in BASES:
            if (mol.name, basis) in SKIPPED_PAIRS:
                continue
            space, active_electrons, active_orbitals, space_note = (
                stage1_active_space(mol, basis)
            )
            common = dict(
                stage="1_screen", mol=mol, basis=basis, active_space=space,
                active_electrons=active_electrons, active_orbitals=active_orbitals,
            )
            for mapper in MAPPERS:
                if skips_mapper(mapper, active_electrons, active_orbitals):
                    continue
                for measurement in MEASUREMENT_METHODS:
                    for ansatz in ANSATZE:
                        rows.append(_row(
                            **common, mapper=mapper, method="VQE",
                            ansatz=ansatz, reps=reps, measurement=measurement,
                            layers_network=None, tn_ansatz=NOT_TN,
                            extra_note=(
                                f"{space_note} Plain-VQE arm of the "
                                f"{ansatz} triple; the TN-VQE and classical-only "
                                "rows on this circuit differ from it in method "
                                "alone."
                            ),
                        ))
                        rows.append(_row(
                            **common, mapper=mapper, method="TN-VQE",
                            ansatz=ansatz, reps=reps, measurement=measurement,
                            layers_network=tn["layers_network"],
                            tn_ansatz=tn["tn_ansatz"].value,
                            extra_note=(
                                f"{space_note} Single TN-VQE reference point "
                                f"(TN_Layers_Network={tn['layers_network']}, "
                                f"{tn['tn_ansatz'].value}, at the circuit's own "
                                f"{reps} repetitions); the full sweep is stage 2."
                            ),
                        ))
                # optimization_mode="network" optimises theta only and takes
                # no quantum measurements at all, so it costs nothing against
                # any plan budget. It is the classical-only floor the "both"
                # rows above must be compared against -- without it, a run
                # whose correlation energy came mostly from the classical
                # orbital rotation reads as a quantum success.
                #
                # One per ansatz, because the control freezes a circuit and
                # the floor it establishes depends on which circuit that is.
                for ansatz in ANSATZE:
                    rows.append(_row(
                        **common, mapper=mapper, method="TN-VQE",
                        ansatz=ansatz, reps=reps, measurement=NETWORK_MODE,
                        layers_network=tn["layers_network"],
                        tn_ansatz=tn["tn_ansatz"].value, optimization_mode="network",
                        extra_note=(
                            f"{space_note} ZERO-QPU CONTROL: "
                            "optimization_mode='network' holds phi at the same "
                            "Phi_Init the other two arms start from and optimises "
                            "theta by classical tensor-network contraction, taking "
                            "no quantum measurements. Costs nothing against any IBM "
                            "plan budget; this is the floor every 'both' row is "
                            "measured against. Num_Opt_Params_Phi is the count held "
                            "FIXED, not optimised."
                        ),
                    ))
    return rows


def _stage2_sweep_points(
    sweep_circuit_ansatz: bool, circuit_ansatz: str,
) -> list[tuple[int, int, str, str]]:
    """The stage-2 (network, circuit, tn_ansatz, circuit_ansatz) points.

    Four families in the 28 points two used to occupy.  Crossing all four
    with the full grid would give 4 + 3*4*4 = 52 points (+83% rows), and
    it is not necessary: the family comparison is a METHOD question, not
    a chemistry-coverage question, so it does not need the full grid on
    every family.

        givens on the full grid:  4 (network=0) + 3 x 4  = 16 points
        family-comparison core:   3 families x network{1,3} x circuit{1,2}
                                                          = 12 points
                                                            ---------
                                                            28 points

    Pinning `givens` rather than rotation_3param as the reference family
    is a deliberate break with the old `full` rows: those used a
    non-entangling U(theta), so they are not a baseline worth preserving
    continuity with.  rotation_3param survives inside the core, which is
    where the comparison against the old default belongs.
    """
    points: list[tuple[int, int, str, str]] = []
    for n_circuit in CIRCUIT_REPS:
        # network=0 is the paper's "circuit only" baseline, so the family
        # has nothing to act on.
        points.append((0, n_circuit, NO_TN_LAYERS, circuit_ansatz))
    for n_network in TN_LAYERS_NETWORK[1:]:
        for n_circuit in CIRCUIT_REPS:
            points.append(
                (n_network, n_circuit, STAGE2_REFERENCE_FAMILY.value, circuit_ansatz)
            )

    # The core doubles under --sweep-circuit-ansatz: with givens or
    # number_preserving, U(theta) commutes with the number operator, so
    # U^dag H U stays in the particle-number sector and the RzRyRz/cx/sca
    # circuit spends depth on amplitude the transformed Hamiltonian cannot
    # use.  excitation_preserving keeps the pipeline in-sector.  The
    # prediction is an INTERACTION, not a main effect -- in-sector circuit
    # helps on number-conserving families, neutral-to-worse on rotation_*
    # ones -- so this stays off the full grid until the core says which
    # way it goes.
    circuit_ansatze = (
        [circuit_ansatz, TN_CIRCUIT_ANSATZ_IN_SECTOR]
        if sweep_circuit_ansatz else [circuit_ansatz]
    )
    for family in STAGE2_CORE_FAMILIES:
        for n_network in STAGE2_CORE_NETWORK:
            for n_circuit in STAGE2_CORE_REPS:
                for circuit in circuit_ansatze:
                    points.append((n_network, n_circuit, family.value, circuit))
    return points


def build_stage2(
    selection: dict[str, str], ansatz: str, active_space: str,
    sweep_circuit_ansatz: bool = False,
) -> list[dict[str, str]]:
    """Full TN-VQE sweep on the basis sets stage 1 selected.

    `selection` maps molecule name -> the basis set carried forward.
    Molecules absent from it are dropped, which is the point: a molecule
    whose stage-1 results were uninformative need not be swept at all.
    """
    rows: list[dict[str, str]] = []
    # The sweep runs on the circuit family stage 1 selected, so a TN-VQE
    # row and the plain-VQE row it is read against share a circuit here
    # too.
    points = _stage2_sweep_points(sweep_circuit_ansatz, ansatz)
    for mol in MOLECULES:
        basis = selection.get(mol.name)
        if basis is None:
            continue
        if active_space == "full" or mol.valence_cas is None:
            # A molecule with no restriction in stage 1 keeps none here:
            # --active-space valence_cas cannot invent a CAS for it.
            row_space = "full"
            active_orbitals = N_SPATIAL_ORBITALS[mol.name][basis]
            active_electrons = mol.num_electrons
            space_note = f"Full space: all {mol.num_electrons} electrons in all {active_orbitals} orbitals."
        else:
            row_space = "valence_cas"
            active_electrons, active_orbitals = mol.valence_cas
            space_note = (
                f"CAS({active_electrons},{active_orbitals}), "
                f"{mol.core_orbitals} core orbital(s) frozen."
            )
        selection_note = f"Stage-2 deep sweep; {basis} carried forward from stage-1 screening. {space_note}"
        common = dict(
            stage="2_deep", mol=mol, basis=basis, active_space=row_space,
            active_electrons=active_electrons, active_orbitals=active_orbitals,
        )
        for mapper in MAPPERS:
            # The same width limit stage 1 screens under: a mapper stage 1
            # never ran cannot have selected anything to sweep here.
            if skips_mapper(mapper, active_electrons, active_orbitals):
                continue
            for measurement in MEASUREMENT_METHODS:
                # A plain-VQE baseline for every circuit shape the sweep
                # runs, not one at a fixed repetition count: the TN row and
                # the VQE row it is read against have to be the same
                # circuit, which is the correction stage 1 carries too.
                for baseline_ansatz, baseline_reps in sorted(
                    {(circuit, n_circuit) for _, n_circuit, _, circuit in points}
                ):
                    rows.append(_row(
                        **common, mapper=mapper, method="VQE",
                        ansatz=baseline_ansatz, reps=baseline_reps,
                        measurement=measurement, layers_network=None,
                        tn_ansatz=NOT_TN,
                        extra_note=(
                            f"{selection_note} Plain-VQE baseline for the TN-VQE "
                            f"rows on {baseline_ansatz} at {baseline_reps} "
                            "repetition(s)."
                        ),
                    ))
                for n_network, n_circuit, tn_ansatz, circuit_ansatz in points:
                    rows.append(_row(
                        **common, mapper=mapper, method="TN-VQE",
                        ansatz=circuit_ansatz, reps=n_circuit,
                        measurement=measurement, layers_network=n_network,
                        tn_ansatz=tn_ansatz,
                        extra_note=selection_note,
                    ))
    return rows


def build_stage3(
    source_rows: list[dict[str, str]],
    refinements: dict[str, pathlib.Path],
    precision: float,
    execution_mode: str,
) -> list[dict[str, str]]:
    """QESEM refinement rows, generated from converged stage-2 results.

    Why this is a stage rather than an arm on stage 1
    -------------------------------------------------
    A refinement row consumes CONVERGED PARAMETERS, and those are not an
    output of stage 1's screen -- they are an output of a converged
    variational run, which is what stage 2 is for.  So the chain is:
    stage 1 selects, stage 2 converges, stage 3 refines what stage 2
    produced.  Same refusal-to-guess as stage 2: there is no defensible
    default set of rows before the prior stage's results exist, so this
    takes explicit `--refine CASE_ID=PARAMS_FILE` pointers and a `σ`.

    Why each refinement is TWO rows
    -------------------------------
    A mitigated energy on its own says nothing about mitigation.  It can
    only be read against the same circuit, at the same parameters, on the
    same device, without QESEM -- so every refinement emits an
    unmitigated row and a mitigated one, identical but for
    `Error_Mitigation`.  Without the pair the arm's headline result is
    "QESEM returned a number", which is not a benchmark finding.  Both
    are then reported as errors against the campaign's classical
    reference energy, which is what turns "the mitigated number is
    different" into "the mitigated number is closer".

    Why they are cheap
    ------------------
    Refinement submits at fixed parameters, so it is one job per row
    rather than one job per optimizer iteration.  The arm is few, late
    and small; it should not look like a sweep.
    """
    by_case_id = {row["Case_ID"]: row for row in source_rows}
    rows: list[dict[str, str]] = []
    for case_id, params_path in refinements.items():
        source = by_case_id.get(case_id)
        if source is None:
            raise SystemExit(
                f"--refine {case_id}=...: no Case_ID {case_id} in the source matrix"
            )
        if not params_path.exists():
            raise SystemExit(
                f"--refine {case_id}={params_path}: converged-parameter file not found. "
                "A refinement row without a pointer to the parameters it refines "
                "produces a number nobody can reproduce."
            )
        digest = hashlib.sha256(params_path.read_bytes()).hexdigest()[:12]
        params_ref = (
            str(params_path.relative_to(_REPO_ROOT))
            if params_path.is_relative_to(_REPO_ROOT) else str(params_path),
            digest,
        )
        for mitigation in (MITIGATION_NONE, MITIGATION_QESEM):
            mitigated = mitigation == MITIGATION_QESEM
            row = dict(source)
            row.update({
                "Case_ID": "",                    # reassigned by write_csv
                "Stage": "3_refine",
                # No optimizer runs: the parameters are already converged,
                # so this is one submission, not one per iteration.
                "Optimizer": "n/a (converged parameters)",
                "Opt_Options": "{}",
                "Iterations": "1",
                "Shots": QESEM_SHOTS if mitigated else str(SHOTS),
                # The mitigated row cannot carry a grouping scheme at all;
                # the unmitigated pair uses `pauli` so the two differ in
                # mitigation and nothing else.
                "Measurement_Method": QESEM_NO_GROUPING if mitigated else "pauli",
                "Phi_Init": "converged (see Converged_Params_File)",
                "Error_Mitigation": mitigation,
                "Precision": f"{precision:g}" if mitigated else SHOT_BASED,
                "QESEM_Execution_Mode": execution_mode if mitigated else NOT_QESEM,
                "Refines_Case_ID": case_id,
                "Converged_Params_File": params_ref[0],
                "Converged_Params_SHA256": params_ref[1],
                "Notes": (
                    f"Stage-3 refinement of stage-2 Case_ID {case_id}, submitted once "
                    f"at its converged parameters. "
                    + (
                        f"QESEM error mitigation at a target precision of "
                        f"{precision:g} Ha ({execution_mode} execution mode). "
                        "QESEM returns a mitigated expectation value with a 1-sigma "
                        "error bar; the ACHIEVED uncertainty is the result and is "
                        "recorded on the job record (QESEMExpectationValue.error_bar), "
                        "not here -- the requested precision is a target, not a "
                        "guarantee, and a job that hits its QPU-time cap first will "
                        "differ. Sampling cost scales as 1/sigma^2, so this column "
                        "sets the arm's budget almost by itself."
                        if mitigated else
                        "UNMITIGATED PAIR: identical circuit, identical parameters, "
                        "same device, no error mitigation. This is the only thing the "
                        "mitigated row can be read against; report both as errors "
                        "against the classical reference energy, not as raw values."
                    )
                    + " QESEM's sampling cost tracks the transformed Hamiltonian's "
                    f"Pauli-term structure, which depends on the TN_Ansatz family "
                    f"that produced this state ({source['TN_Ansatz']}) -- refining a "
                    "number_preserving state is not the same price as refining a "
                    "givens one."
                ),
            })
            rows.append(row)
    return rows


def write_csv(path: pathlib.Path, rows: list[dict[str, str]]) -> None:
    for i, row in enumerate(rows, start=1):
        row["Case_ID"] = str(i)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: list[dict[str, str]]) -> None:
    qubits = sorted({int(r["N_Qubit"]) for r in rows})
    print(f"  {len(rows)} rows, qubit counts {qubits[0]}-{qubits[-1]}")
    for mapper in MAPPERS:
        subset = [r for r in rows if r["Mapper"] == mapper]
        inferred = sum(1 for r in subset if r["N_Qubit_Source"] == "mol_map_inferred")
        suffix = f" ({inferred} qubit counts inferred, not from a real MOL_MAP run)" if inferred else ""
        print(f"    {mapper}: {len(subset)} rows{suffix}")
    controls = [r for r in rows if r["Optimization_Mode"] == "network"]
    if controls:
        print(f"    {len(controls)} zero-QPU classical-only controls "
              f"(optimization_mode='network')")
    families = sorted({r["TN_Ansatz"] for r in rows if not r["TN_Ansatz"].startswith("n/a")})
    if families:
        print(f"    TN families: {', '.join(families)}")


def _read_source_matrix(path: pathlib.Path | None) -> list[dict[str, str]]:
    """The stage-2 matrix a stage-3 arm refines."""
    if path is None:
        raise SystemExit(
            "stage 3 needs --from STAGE2_CSV: a refinement row refines a specific "
            "converged run, and there is nothing to point at until stage 2 has run"
        )
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _parse_refinements(pairs: list[str]) -> dict[str, pathlib.Path]:
    if not pairs:
        raise SystemExit(
            "stage 3 needs at least one --refine CASE_ID=PARAMS_FILE. Which rows "
            "deserve refinement is an output of stage 2 -- best energy, widest "
            "spread against the classical reference, or one per molecule -- and "
            "the criterion should be written down before stage 2 runs rather than "
            "chosen afterwards from the results"
        )
    refinements: dict[str, pathlib.Path] = {}
    for pair in pairs:
        case_id, _, params = pair.partition("=")
        if not params:
            raise SystemExit(f"--refine wants CASE_ID=PARAMS_FILE; got {pair!r}")
        refinements[case_id] = pathlib.Path(params)
    return refinements


def _require_precision(precision: float | None) -> float:
    if precision is None:
        raise SystemExit(
            "stage 3 needs --precision SIGMA (Hartree). It is not a column to be "
            "filled in later: sigma sets what the arm costs and what it can "
            "conclude. Chemical accuracy is ~1.6e-3 Ha, and an energy quoted to "
            "+/-0.1 Ha cannot distinguish basis sets, ansaetze or mappers -- which "
            "is the campaign's whole purpose. Do not inherit a service default: "
            "those are set for general use and are far looser than chemistry needs"
        )
    if precision <= 0:
        raise SystemExit(f"--precision must be positive; got {precision}")
    return precision


def _parse_selection(pairs: list[str]) -> dict[str, str]:
    selection: dict[str, str] = {}
    known = {m.name for m in MOLECULES}
    for pair in pairs:
        molecule, _, basis = pair.partition("=")
        if molecule not in known:
            raise SystemExit(f"unknown molecule {molecule!r}; expected one of {sorted(known)}")
        if basis not in BASES:
            raise SystemExit(f"unknown basis {basis!r}; expected one of {BASES}")
        reason = SKIPPED_PAIRS.get((molecule, basis))
        if reason is not None:
            raise SystemExit(
                f"--select {molecule}={basis}: stage 1 does not screen this pair "
                f"({reason}), so there is no stage-1 result to carry forward"
            )
        selection[molecule] = basis
    return selection


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stage", choices=["1", "2", "3"], default="1")
    parser.add_argument(
        "--select", action="append", default=[], metavar="MOLECULE=BASIS",
        help="stage 2 only: basis set carried forward from stage-1 results",
    )
    parser.add_argument(
        "--ansatz", default="EfficientSU2",
        help="stage 2 only: VQE ansatz carried forward from stage-1 results",
    )
    parser.add_argument(
        "--active-space", choices=["valence_cas", "full"], default="valence_cas",
        help="stage 2 only: 'full' needs a machine that can run it (see data/benchmarks/ibm_tn-vqe_qesem/README.md)",
    )
    parser.add_argument(
        "--sweep-circuit-ansatz", action="store_true",
        help=(
            "stage 2 only: also sweep the circuit ansatz (the selected family "
            "vs excitation_preserving_linear) over the 12-point family-comparison "
            "core. Doubles the core, taking the sweep from 28 to 40 points and "
            "the file from 256 to 368 rows -- re-cost before running it, "
            "xx_plus_yy is not an IBM basis gate on any current device"
        ),
    )
    parser.add_argument(
        "--from", dest="source", type=pathlib.Path, default=None,
        help="stage 3 only: the stage-2 matrix whose rows are being refined",
    )
    parser.add_argument(
        "--refine", action="append", default=[], metavar="CASE_ID=PARAMS_FILE",
        help=(
            "stage 3 only: refine this stage-2 case, using the converged "
            "theta/phi in PARAMS_FILE. Repeatable."
        ),
    )
    parser.add_argument(
        "--precision", type=float, default=None, metavar="SIGMA",
        help=(
            "stage 3 only: QESEM target precision in Hartree. No default -- it "
            "sets what the arm costs AND what it can conclude, so it has to be "
            "chosen. Chemical accuracy is ~1.6e-3 Ha; sampling cost scales as "
            "1/sigma^2, so a loose sigma buys a mitigation demonstration and a "
            "tight one buys a chemistry result"
        ),
    )
    parser.add_argument(
        "--execution-mode", choices=["batch", "session"], default="batch",
        help="stage 3 only: QESEM QPU reservation strategy (batch releases the "
             "QPU during classical steps, and is cheaper)",
    )
    parser.add_argument("-o", "--output", type=pathlib.Path, default=None)
    args = parser.parse_args()

    if args.stage == "1":
        rows = build_stage1()
        path = args.output or _STAGE1_PATH
    elif args.stage == "3":
        rows = build_stage3(
            _read_source_matrix(args.source),
            _parse_refinements(args.refine),
            _require_precision(args.precision),
            args.execution_mode,
        )
        path = args.output or _STAGE3_PATH
    else:
        selection = _parse_selection(args.select)
        if not selection:
            raise SystemExit(
                "stage 2 needs at least one --select MOLECULE=BASIS, chosen from "
                "stage-1 results -- there is no defensible default before those exist"
            )
        rows = build_stage2(
            selection, args.ansatz, args.active_space, args.sweep_circuit_ansatz,
        )
        path = args.output or _STAGE2_PATH

    write_csv(path, rows)
    # -o may point anywhere, so only shorten paths that are really inside
    # the repo.
    shown = path.relative_to(_REPO_ROOT) if path.is_relative_to(_REPO_ROOT) else path
    print(f"Wrote {shown}")
    summarize(rows)


if __name__ == "__main__":
    main()
