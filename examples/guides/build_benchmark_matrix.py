"""Build the VQE benchmark scenario matrix, in two stages.

Writes `data/IBM_VQE_Test_Benchmark.csv` (stage 1) and, once stage-1
results are in, a stage-2 deep-sweep file for the basis sets and ansatz
that earned it.

Requires: nothing beyond the standard library.

Why two stages
--------------
An earlier revision of this matrix crossed every dimension with every
other: 3 molecules x 7 basis sets x 2 mappers x 28 TN-VQE sweep points x
2 measurement methods = 2,436 rows, ~2,463 minutes of estimated QPU time,
and no mechanism for *deciding* anything -- every basis set got the full
28-point tensor-network sweep whether or not it was worth one.

The sweep is now split at its natural decision point:

  Stage 1 (screening) -- broad in the things you are choosing *between*
    (all 7 basis sets, several ansaetze, both mappers, both measurement
    methods), shallow in everything else (one reference TN-VQE point, one
    small fixed active space per molecule).  294 rows.

  Stage 2 (deep sweep) -- the full 28-point TN_Layers_Network x
    TN_Layers_Circuit x Rotation_Type sweep, run only on the (molecule,
    basis, ansatz) combinations stage 1 says are worth it.  Generated by
    re-running this script with `--stage 2 --select ...` once you have
    stage-1 results; not committed in advance, because the selection is
    an output of stage 1, not an input to it.

Every stage-1 row holds the active space *fixed across basis sets* for a
given molecule, which is what makes the comparison a basis-set screen
rather than a confound: only the basis varies, so the resulting energies
are attributable to it.

Run:
    python examples/guides/build_benchmark_matrix.py
    python examples/guides/build_benchmark_matrix.py --stage 2 \\
        --select H2=cc-pvdz --select Li2=6-31g --select H2O=def2-svp \\
        --ansatz EfficientSU2
"""
from __future__ import annotations

import argparse
import csv
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))

from qpubench.hamiltonian_sources.mol_map import count_qubits, is_confirmed

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_STAGE1_PATH = _REPO_ROOT / "data" / "IBM_VQE_Test_Benchmark.csv"
_STAGE2_PATH = _REPO_ROOT / "data" / "stage2_deep_sweep.csv"


# --- Molecules ------------------------------------------------------------
#
# All three are neutral closed-shell singlets, so n_alpha = n_beta =
# num_electrons / 2 throughout.

class Molecule:
    def __init__(self, name: str, num_electrons: int, core_orbitals: int,
                 valence_cas: tuple[int, int]) -> None:
        self.name = name
        self.num_electrons = num_electrons
        self.core_orbitals = core_orbitals      # frozen in `valence_cas`
        self.valence_cas = valence_cas          # (active electrons, active orbitals)


MOLECULES = [
    # H2 has no core to freeze; its "valence" CAS(2,2) is the minimal
    # active space, used in stage 1 to hold the space fixed across bases.
    Molecule("H2",  num_electrons=2,  core_orbitals=0, valence_cas=(2, 2)),
    # Li2: freeze both Li 1s orbitals, leaving the 2s-derived sigma pair.
    Molecule("Li2", num_electrons=6,  core_orbitals=2, valence_cas=(2, 2)),
    # H2O: freeze O 1s; CAS(8,6) is the standard water valence space
    # (2a1, 1b2, 3a1, 1b1 occupied plus the 4a1/2b2 valence virtuals).
    Molecule("H2O", num_electrons=10, core_orbitals=1, valence_cas=(8, 6)),
]

# Spatial orbital count per (molecule, basis) -- i.e. half the
# Jordan-Wigner qubit count of the full space.  Cross-checked against
# real `pyscf.gto.M(...).nao` values; see tests/test_basis_sets.py and
# tests/test_qvszp.py.
N_SPATIAL_ORBITALS = {
    "H2":  {"sto-3g": 2,  "6-31g": 4,  "cc-pvdz": 10, "cc-pvtz": 28,
            "def2-svp": 10, "def2-tzvp": 12, "qvSZP": 8},
    "Li2": {"sto-3g": 10, "6-31g": 18, "cc-pvdz": 28, "cc-pvtz": 60,
            "def2-svp": 18, "def2-tzvp": 28, "qvSZP": 18},
    "H2O": {"sto-3g": 7,  "6-31g": 13, "cc-pvdz": 24, "cc-pvtz": 58,
            "def2-svp": 24, "def2-tzvp": 43, "qvSZP": 17},
}

BASES = ["sto-3g", "6-31g", "cc-pvdz", "cc-pvtz", "def2-svp", "def2-tzvp", "qvSZP"]
BASIS_SOURCE = {b: "basis_set_exchange" for b in BASES} | {"qvSZP": "grimme_qvszp"}

MAPPERS = ["JW", "mol_map"]
MEASUREMENT_METHODS = ["pauli", "grouped"]

# --- Ansaetze -------------------------------------------------------------
#
# UCCSD builds its excitation operators from fermionic modes, so it needs
# a fermion-to-qubit mapping to sit on: available on JW, not on mol_map's
# constraint encoding (whose qubits index determinants, not spin
# orbitals).  The hardware-efficient families work on either.

VQE_ANSATZE = {
    "JW":      ["EfficientSU2", "RealAmplitudes", "UCCSD"],
    "mol_map": ["EfficientSU2", "RealAmplitudes"],
}
TN_VQE_ANSATZ = "StronglyEntanglingLayers"   # Cebule TN_QC_OPT's circuit side

# The single TN-VQE point stage 1 runs, mid-range in both directions --
# enough to tell whether TN-VQE helps for a given basis without paying
# for the full 28-point sweep.
STAGE1_TN_REFERENCE = {"layers_network": 2, "layers_circuit": 2, "rotation": "full"}

# Stage 2's full sweep, matching the reference paper (arXiv:2402.12105).
TN_LAYERS_NETWORK = [0, 1, 2, 3]
TN_LAYERS_CIRCUIT = [1, 2, 3, 4]
ROTATION_TYPES = ["full", "phase"]

OPTIMIZER = "COBYLA"

FIELDNAMES = [
    "Case_ID", "Stage", "Molecule", "Charge", "Multiplicity", "Num_Electrons",
    "Basis", "Basis_Source", "Active_Space", "Active_Electrons", "Active_Orbitals",
    "Mapper", "N_Qubit", "N_Qubit_Source", "Method", "Ansatz", "Ansatz_Reps",
    "Optimizer", "Qiskit_Opt_Level", "Shots", "TN_Layers_Network",
    "TN_Layers_Circuit", "Rotation_Type", "Measurement_Method",
    "Num_Opt_Params_Phi", "Num_Opt_Params_Theta", "Num_ExpVals_Per_Iter", "Notes",
]


def qubit_count(mapper: str, active_electrons: int, active_orbitals: int) -> tuple[int, str]:
    """(qubits, provenance) for one active space under one mapper."""
    if mapper == "JW":
        return 2 * active_orbitals, "jw_exact"
    n_alpha = n_beta = active_electrons // 2
    n = count_qubits(active_orbitals, n_alpha, n_beta)
    assert n is not None
    source = "mol_map_run" if is_confirmed(active_orbitals, n_alpha, n_beta) else "mol_map_inferred"
    return n, source


def circuit_parameter_count(ansatz: str, num_qubits: int, reps: int) -> str:
    """Circuit-side (phi) parameter count, where the ansatz fixes it.

    UCCSD's count depends on the excitation list its builder generates
    from the active space, not on (qubits, reps) alone, so it is left to
    the real run.
    """
    if ansatz == "StronglyEntanglingLayers":
        return str(3 * reps * num_qubits)          # PennyLane's (L, N, 3) shape
    if ansatz == "EfficientSU2":
        return str(2 * num_qubits * (reps + 1))    # 2 rotation layers per block
    if ansatz == "RealAmplitudes":
        return str(num_qubits * (reps + 1))        # 1 rotation layer per block
    return ""


def _qubit_note(mapper: str, source: str, molecule: str, basis: str) -> str:
    if mapper == "JW":
        return "N_Qubit = 2 x active orbitals (exact)."
    if source == "mol_map_run":
        return f"N_Qubit confirmed by a real Cebule MOL_MAP run for {molecule}/{basis}."
    return (
        "N_Qubit predicted by hamiltonian_sources.mol_map's inferred "
        "constraint-encoding formula, not a real MOL_MAP run -- exact for "
        "all 8 counts real runs have reported, but an estimate here."
    )


def _measurement_note(method: str) -> str:
    if method == "pauli":
        return "Standard per-Pauli-string measurement (baseline)."
    return (
        "Cebule's basis-state-pair-grouping measurement scheme "
        "(TNQCOptInput.measurement_method='grouped'). Expected to need "
        "fewer or equal distinct circuits per iteration than 'pauli', but "
        "the exact circuit count is an output of a real run, not "
        "predictable from the inputs."
    )


def _row(
    *, stage: str, mol: Molecule, basis: str, active_space: str,
    active_electrons: int, active_orbitals: int, mapper: str, method: str,
    ansatz: str, reps: int, measurement: str,
    layers_network: int | None, layers_circuit: int | None, rotation: str,
    extra_note: str = "",
) -> dict[str, str]:
    num_qubits, source = qubit_count(mapper, active_electrons, active_orbitals)
    notes = [_qubit_note(mapper, source, mol.name, basis)]
    if extra_note:
        notes.append(extra_note)
    notes.append(_measurement_note(measurement))
    return {
        "Case_ID": "",                       # assigned after the full list is built
        "Stage": stage,
        "Molecule": mol.name,
        "Charge": "0",
        "Multiplicity": "1",
        "Num_Electrons": str(mol.num_electrons),
        "Basis": basis,
        "Basis_Source": BASIS_SOURCE[basis],
        "Active_Space": active_space,
        "Active_Electrons": str(active_electrons),
        "Active_Orbitals": str(active_orbitals),
        "Mapper": mapper,
        "N_Qubit": str(num_qubits),
        "N_Qubit_Source": source,
        "Method": method,
        "Ansatz": ansatz,
        "Ansatz_Reps": str(reps),
        "Optimizer": OPTIMIZER,
        "Qiskit_Opt_Level": "",
        "Shots": "",
        "TN_Layers_Network": "" if layers_network is None else str(layers_network),
        "TN_Layers_Circuit": "" if layers_circuit is None else str(layers_circuit),
        "Rotation_Type": rotation,
        "Measurement_Method": measurement,
        "Num_Opt_Params_Phi": circuit_parameter_count(ansatz, num_qubits, reps),
        "Num_Opt_Params_Theta": "",
        "Num_ExpVals_Per_Iter": "",
        "Notes": " ".join(notes),
    }


def build_stage1() -> list[dict[str, str]]:
    """Screening matrix: which basis set, which ansatz, which mapper.

    The active space is `mol.valence_cas` for every row, identical across
    all 7 basis sets, so a stage-1 energy difference between two bases is
    attributable to the basis rather than to a differently-sized space.
    """
    rows: list[dict[str, str]] = []
    tn = STAGE1_TN_REFERENCE
    for mol in MOLECULES:
        active_electrons, active_orbitals = mol.valence_cas
        cas_note = (
            f"Stage-1 screening active space CAS({active_electrons},"
            f"{active_orbitals}), held fixed across all basis sets"
            + (f"; {mol.core_orbitals} core orbital(s) frozen." if mol.core_orbitals
               else " (H2 has no core to freeze).")
        )
        for basis in BASES:
            for mapper in MAPPERS:
                for measurement in MEASUREMENT_METHODS:
                    for ansatz in VQE_ANSATZE[mapper]:
                        rows.append(_row(
                            stage="1_screen", mol=mol, basis=basis,
                            active_space="valence_cas",
                            active_electrons=active_electrons,
                            active_orbitals=active_orbitals,
                            mapper=mapper, method="VQE", ansatz=ansatz, reps=1,
                            measurement=measurement, layers_network=None,
                            layers_circuit=None, rotation="n/a (not TN-VQE)",
                            extra_note=cas_note,
                        ))
                    rows.append(_row(
                        stage="1_screen", mol=mol, basis=basis,
                        active_space="valence_cas",
                        active_electrons=active_electrons,
                        active_orbitals=active_orbitals,
                        mapper=mapper, method="TN-VQE", ansatz=TN_VQE_ANSATZ,
                        reps=tn["layers_circuit"], measurement=measurement,
                        layers_network=tn["layers_network"],
                        layers_circuit=tn["layers_circuit"],
                        rotation=tn["rotation"],
                        extra_note=(
                            f"{cas_note} Single TN-VQE reference point "
                            f"(network={tn['layers_network']}, circuit="
                            f"{tn['layers_circuit']}, {tn['rotation']} rotation); "
                            "the full sweep is stage 2."
                        ),
                    ))
    return rows


def build_stage2(
    selection: dict[str, str], ansatz: str, active_space: str,
) -> list[dict[str, str]]:
    """Full TN-VQE sweep on the basis sets stage 1 selected.

    `selection` maps molecule name -> the basis set carried forward.
    Molecules absent from it are dropped, which is the point: a molecule
    whose stage-1 results were uninformative need not be swept at all.
    """
    rows: list[dict[str, str]] = []
    for mol in MOLECULES:
        basis = selection.get(mol.name)
        if basis is None:
            continue
        if active_space == "full":
            active_orbitals = N_SPATIAL_ORBITALS[mol.name][basis]
            active_electrons = mol.num_electrons
            space_note = f"Full space: all {mol.num_electrons} electrons in all {active_orbitals} orbitals."
        else:
            active_electrons, active_orbitals = mol.valence_cas
            space_note = (
                f"CAS({active_electrons},{active_orbitals})"
                + (f", {mol.core_orbitals} core orbital(s) frozen." if mol.core_orbitals
                   else " (H2 has no core to freeze).")
            )
        selection_note = f"Stage-2 deep sweep; {basis} carried forward from stage-1 screening. {space_note}"
        for mapper in MAPPERS:
            for measurement in MEASUREMENT_METHODS:
                # Vanilla VQE reference at the selected ansatz, for the
                # TN-VQE rows to be measured against.
                rows.append(_row(
                    stage="2_deep", mol=mol, basis=basis, active_space=active_space,
                    active_electrons=active_electrons, active_orbitals=active_orbitals,
                    mapper=mapper, method="VQE", ansatz=ansatz, reps=1,
                    measurement=measurement, layers_network=None,
                    layers_circuit=None, rotation="n/a (not TN-VQE)",
                    extra_note=f"{selection_note} Vanilla-VQE baseline for the TN-VQE sweep.",
                ))
                for n_network in TN_LAYERS_NETWORK:
                    # network=0 is the paper's "circuit only" baseline, so
                    # the rotation type has nothing to act on.
                    rotations = ["n/a (no TN layers)"] if n_network == 0 else ROTATION_TYPES
                    for n_circuit in TN_LAYERS_CIRCUIT:
                        for rotation in rotations:
                            rows.append(_row(
                                stage="2_deep", mol=mol, basis=basis,
                                active_space=active_space,
                                active_electrons=active_electrons,
                                active_orbitals=active_orbitals,
                                mapper=mapper, method="TN-VQE",
                                ansatz=TN_VQE_ANSATZ, reps=n_circuit,
                                measurement=measurement,
                                layers_network=n_network, layers_circuit=n_circuit,
                                rotation=rotation, extra_note=selection_note,
                            ))
    return rows


def write_csv(path: pathlib.Path, rows: list[dict[str, str]]) -> None:
    for i, row in enumerate(rows, start=1):
        row["Case_ID"] = str(i)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: list[dict[str, str]]) -> None:
    qubits = sorted({int(r["N_Qubit"]) for r in rows})
    print(f"  {len(rows)} rows, qubit counts {qubits[0]}-{qubits[-1]}")
    for mapper in MAPPERS:
        subset = [r for r in rows if r["Mapper"] == mapper]
        inferred = sum(1 for r in subset if r["N_Qubit_Source"] == "mol_map_inferred")
        suffix = f" ({inferred} qubit counts inferred, not from a real MOL_MAP run)" if inferred else ""
        print(f"    {mapper}: {len(subset)} rows{suffix}")


def _parse_selection(pairs: list[str]) -> dict[str, str]:
    selection: dict[str, str] = {}
    known = {m.name for m in MOLECULES}
    for pair in pairs:
        molecule, _, basis = pair.partition("=")
        if molecule not in known:
            raise SystemExit(f"unknown molecule {molecule!r}; expected one of {sorted(known)}")
        if basis not in BASES:
            raise SystemExit(f"unknown basis {basis!r}; expected one of {BASES}")
        selection[molecule] = basis
    return selection


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stage", choices=["1", "2"], default="1")
    parser.add_argument(
        "--select", action="append", default=[], metavar="MOLECULE=BASIS",
        help="stage 2 only: basis set carried forward from stage-1 results",
    )
    parser.add_argument(
        "--ansatz", default="EfficientSU2",
        help="stage 2 only: VQE ansatz carried forward from stage-1 results",
    )
    parser.add_argument(
        "--active-space", choices=["valence_cas", "full"], default="valence_cas",
        help="stage 2 only: 'full' needs a machine that can run it (see data/README.md)",
    )
    parser.add_argument("-o", "--output", type=pathlib.Path, default=None)
    args = parser.parse_args()

    if args.stage == "1":
        rows = build_stage1()
        path = args.output or _STAGE1_PATH
    else:
        selection = _parse_selection(args.select)
        if not selection:
            raise SystemExit(
                "stage 2 needs at least one --select MOLECULE=BASIS, chosen from "
                "stage-1 results -- there is no defensible default before those exist"
            )
        rows = build_stage2(selection, args.ansatz, args.active_space)
        path = args.output or _STAGE2_PATH

    write_csv(path, rows)
    # -o may point anywhere, so only shorten paths that are really inside
    # the repo.
    shown = path.relative_to(_REPO_ROOT) if path.is_relative_to(_REPO_ROOT) else path
    print(f"Wrote {shown}")
    summarize(rows)


if __name__ == "__main__":
    main()
