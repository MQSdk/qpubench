"""Public schema namespace.

Every model, enum and constant in the three groups below is re-exported here,
so ``from qpubench.schemas import CircuitSpec`` (and ``from qpubench import
CircuitSpec``) is the stable import path regardless of which file a type lives
in. The layout underneath it:

    schemas/            core record format — the seven modules every
                        benchmark shares, from primitives through record.
    schemas/catalogs/   cross-cutting catalogues and registries: modules that
                        aggregate several external sources, or define a
                        qpubench-owned catalogue. Neither core types nor a
                        mirror of one upstream project.
    schemas/mirrors/    one module per external project, named
                        <org_or_maintainer>_<package>.py so the filename says
                        who maintains the upstream and what it is called.

See docs/schemas.md for the full module index and docs/developer_guide.md for
the naming conventions.
"""
