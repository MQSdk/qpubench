# scipy.optimize.minimize does NOT honour a maxiter below that -- it
# raises maxfun, warns "COBYLA: Invalid MAXFUN; it should be at least
# ...", and runs n+2 evaluations anyway.  A budget set under n+2
# therefore does not make a row cheaper, it only misstates what the row
# costs, which is how a flat 30 came to under-bill the widest rows by
# ~4.8x.
#
# The reason for proportional rather than n + constant is a different
# one, and it is about what stage 1 can conclude.  COBYLA needs
# evaluations in proportion to n to make a given amount of progress:
# measured on a trigonometric-polynomial objective (the functional form a
# VQE energy takes), reaching a fixed fraction of the achievable descent
# costs about 1.3n evaluations for 50%, 4n for 80% and 12n for 95%.  So a
# rule of the form `n + constant` delivers a SHRINKING fraction as n
# grows -- fraction of achievable descent, median over seeds:
#
#      n     max(30,n+2)     n+30     n+100     1.3n      2n      4n
#     22          53%         65%       85%      53%     61%     79%
#     46          41%         54%       75%      47%     64%     81%
#     94          38%         51%       65%      50%     63%     81%
#    142          38%         49%       60%      51%     65%     85%
#    200          38%         47%       54%      51%     62%     80%
#
# The additive columns fall, the proportional ones are flat.  Under
# `n + 2` a row reached 53% of its own achievable descent at n=22 and 38%
# at n=200, which made the optimizer budget a confound correlated with
# the qubit count -- and the qubit count is one of the factors the screen
# exists to compare.  Under the proportional rule every row reaches ~50%,
# so "convergence behaviour", stage 1's stated observable, is comparable
# across rows.  It also equalises a control against the row it controls:
# a `network` row varies theta only and its `both` counterpart varies phi
# and theta, so under an additive rule the control was run much further
# along its own convergence curve than the row it is the baseline for.
#
# Stage 1 remains a SCREEN: ~50% of achievable descent ranks rows and
# exposes the initial descent, and it is not a converged energy.  Stage 2
# carries the converged runs at the same functional form and a larger
# multiplier.
#
# The multipliers come from a synthetic objective, so they are the right
# functional form and the right order of magnitude rather than tuned
# values.  `TN_QC_OPT` already returns `cost_history`, one entry per
# cost-function evaluation, so real runs refine them with no new
# instrumentation and no schema change.
MIN_ITERATIONS = 30       # smoke-test floor, so the small rows stay comparable
SIMPLEX_OVERHEAD = 2      # n+1 simplex points, +1 for the first real step;
                          # retained as the invariant the rule must never breach
STAGE1_EVALS_PER_PARAM = 1.3   # ~50% of achievable descent, at every width
STAGE2_EVALS_PER_PARAM = 4.0   # ~80%; stage 2 is where converged energies live

# --- phi_init, per circuit family -----------------------------------------
#
# phi is the CIRCUIT's parameter vector, so every row has one: a plain
# VQE row has circuit parameters exactly as a TN-VQE row does, and a
# `network` row has them frozen rather than absent.  The initialisation
# is therefore a property of the CIRCUIT FAMILY, not of the method and
# not of the optimization mode.  Keying it that way is what makes the
# comparison a comparison: two rows that share (ansatz, qubits, reps)
# start from the same state whatever else differs between them, so a
# difference in the result is attributable to the method.
#
# Upstream randomises phi (2*pi*random, run_TNQCOpt) whenever phi_init is
# None, and does so unseeded -- so an unpinned run has an initialisation
# nobody can reproduce.  That is the defect the pin fixes; the value is
# then chosen per family:
#
#   Hardware-efficient families (EfficientSU2, RealAmplitudes, ...) take
#   a SEEDED RANDOM DRAW.  All-zero rotations
#   make these circuits the identity, so the initial state is the
#   reference determinant and the gradient with respect to many phi
#   parameters vanishes there -- a well-known bad start.  Seeding keeps
#   reproducibility without changing the character of the
#   initialisation, and it matches upstream's own default.
#
#   UCCSD takes ZEROS, because zero amplitudes ARE the Hartree-Fock
#   reference: t=0 is the standard, and the only defensible, start for a
#   coupled-cluster ansatz, and randomising it would be an experimental
#   choice rather than a reproducibility fix.  No stage-1 row takes this
#   branch -- UCCSD is not in ANSATZE -- but a later stage naming UCCSD
#   would, and the rule belongs with the others rather than with the
#   stage that happens to use it.
#
# The seed is the date the convention was settled.  The campaign draws
# 2*pi*U(0,1) from numpy's default_rng(seed) -- upstream's distribution --
# and passes the vector explicitly through phi_init, because upstream
# exposes no seed of its own.
PHI_INIT_SEED = 20260811
PHI_INIT_ZEROS = "zeros"
PHI_INIT_RANDOM = f"random(seed={PHI_INIT_SEED})"
# Families for which zero is the reference state rather than a barren one.
PHI_INIT_ZEROS_ANSATZE = {"UCCSD"}

# --- Measurement circuits per cost-function evaluation -------------------
#
# Evaluating <H> costs one circuit per measurement basis, not one circuit
# per evaluation, and that count is a property of the Hamiltonian.  It is
# recorded per row in Num_ExpVals_Per_Iter, with its provenance in
# Num_ExpVals_Source, because the campaign's QPU cost is proportional to
# it.
#
#   measured_run    counted on a real ibm_aachen Estimator job of the same
#                   active space (see docs/integrations/ibm_cost_estimator.md)
#   qwc_grouping    computed offline by qubit-wise-commuting grouping of the
#                   row's own Hamiltonian, utils/count_measurement_bases.py.
#                   Greedy and order-dependent, so an upper bound: the one
#                   class where both numbers exist reads 34 measured against
#                   46 computed
#   hamiltonian_file  counted on the committed operator the run actually
#                   optimises (data/benchmarks/.../hamiltonian_data), by
#                   qubit-wise-commuting grouping.  Greedy, so an upper
#                   bound on what the runtime's own grouping achieves.
#
# There is no longer an `assumed` class.  Every screened combination has a
# committed Hamiltonian, and the assumption it replaced was wrong by up to
# 36x: mol_map H2/cc-pVDZ was carried at 37 and counts 1,322, because the
# constraint encoding trades qubits for density -- 10,069 Pauli terms on 7
# qubits.  That single correction is why the campaign was rescoped.
#
# Where both a measurement and a count exist they disagree by about 2x
# (H2/6-31g JW: 34 billed against 68 counted), the runtime grouping being
# better than greedy.  The measured value is used where there is one, and
# the counted value is an upper bound everywhere else -- which is what
# stage 0 exists to replace with measurement.
#
# Keyed on (mapper, molecule, qubits) rather than on the basis, because
# the basis does not move the count where both are screened: water's
# committed Hamiltonians at CAS(4,4) are 105 Pauli strings under JW and
# 1,328 under mol_map in EVERY basis, the same structure with different
# coefficients, so its two bases group identically.  H2 is unrestricted,
# so its two bases land at different widths and are keyed apart by the
# qubit count already.
